const { chromium } = require('playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const base = require('node:path').resolve(__dirname, '..');
(async () => {
 const variant = process.argv[2] || 'grace';
 assert.ok(['grace','carian','destined','farum','ring'].includes(variant));
 const urlFile = variant === 'grace' ? 'live-preview-url.txt' : 'live-preview-'+variant+'-url.txt';
 const out = base+'/previews/browser-'+variant;
 fs.mkdirSync(out,{recursive:true});
 const url = fs.readFileSync(base+'/'+urlFile,'utf8').trim();
 const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless:true, args:['--no-sandbox']});
 const page = await browser.newPage({viewport:{width:1440,height:960}});
 const errors=[]; page.on('pageerror', e=>errors.push(e.message));
 const posts=[]; page.on('request', r=>{if(r.method()==='POST')posts.push(r.postDataJSON().key)});
 await page.goto(url);
 await page.waitForSelector('main.ready', {timeout:20000});
 await page.waitForTimeout(1500);
 await page.screenshot({path:out+'/desktop.png'});
 await page.keyboard.press('ArrowDown');
 await page.waitForTimeout(500);
 await page.getByRole('button',{name:'Previous boot entry'}).click();
 await page.waitForTimeout(500);
 assert.deepEqual(posts.slice(0,2),['down','up']);
 await page.getByRole('button',{name:'PAUSE VIEW',exact:true}).click();
 await page.waitForTimeout(500);
 const pausedSrc=await page.locator('#screen').getAttribute('src');
 await page.waitForTimeout(350);
 assert.equal(await page.locator('#screen').getAttribute('src'),pausedSrc);
 await page.getByRole('button',{name:'RESUME VIEW',exact:true}).click();
 await page.waitForTimeout(300);
 assert.notEqual(await page.locator('#screen').getAttribute('src'),pausedSrc);
 await page.getByRole('button',{name:'FULLSCREEN',exact:true}).click();
 await page.waitForTimeout(150);
 assert.equal(await page.evaluate(()=>document.fullscreenElement?.id),'display');
 await page.evaluate(()=>document.exitFullscreen());
 await page.keyboard.press('Home');
 const token = new URL(url).searchParams.get('token');
 const origin = new URL(url).origin;
 assert.equal((await page.request.get(origin+'/')).status(),403);
 assert.equal((await page.request.post(origin+'/key?token='+token,{data:{key:'delete'}})).status(),400);
 const mobile=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce',isMobile:true,hasTouch:true});
 mobile.on('pageerror',e=>errors.push(e.message));
 await mobile.goto(url);
 await mobile.waitForSelector('main.ready');
 assert.equal(await mobile.locator('#pause').getAttribute('aria-pressed'),'true');
 assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.ok(await mobile.locator('#fullscreen').evaluate(el=>el.getBoundingClientRect().bottom <= innerHeight));
 await mobile.screenshot({path:out+'/mobile.png'});
 await mobile.getByRole('button',{name:'Next boot entry'}).click();
 await mobile.waitForTimeout(500);
 await mobile.getByRole('button',{name:'Previous boot entry'}).click();
 assert.deepEqual(errors,[]);
 const report={variant,passed:true,keyboard:true,buttons:true,pause_and_resume:true,fullscreen:true,token_required:true,invalid_key_rejected:true,mobile_no_horizontal_overflow:true,reduced_motion_respected:true,page_errors:errors};
 fs.writeFileSync(out+'/validation.json',JSON.stringify(report,null,2));
 console.log(JSON.stringify(report,null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
